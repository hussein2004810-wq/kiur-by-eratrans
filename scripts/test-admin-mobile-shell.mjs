import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';

const source=await readFile('src/RealAppV2.tsx','utf8');
const shell=await readFile('src/stitch/components/StitchAdminWorkspace.tsx','utf8');
const css=await readFile('src/stitch/stitch-admin.css','utf8');
assert(source.includes("StitchAdminWorkspace"),'real admin managers must use the Stitch admin workspace');
assert(source.includes("useState<AdminSectionId>('overview')"),'admin must open on a real operational overview');
assert.equal((source.match(/id:'(?:overview|tests|imports|catalog|students|academicChanges|gamification|glimpses|library|accounts|bans|logs)'/g)||[]).length,12,'all admin destinations must be declared once');
const realAppBody=source.slice(source.indexOf('export default function RealAppV2'));
const earlyReturn=realAppBody.indexOf('if(authPreview');
assert(earlyReturn>0,'RealAppV2 must contain early return block');
const invalidHook=realAppBody.slice(earlyReturn).match(/\buse(?:Effect|State|Memo|Callback|Ref|Context|Reducer|LayoutEffect)\b/);
assert(!invalidHook,`React Hook "${invalidHook?.[0]}" must not be called after conditional return in RealAppV2`);
assert(shell.includes('setMenuOpen(false)'),'choosing a destination must close the phone menu');
assert(shell.includes('aria-controls="stitch-admin-nav"')&&shell.includes('aria-expanded={menuOpen}'),'phone menu state must be announced');
assert(shell.includes("active==='overview'")&&shell.includes('لا نستخدم بيانات تجريبية'),'overview must use honest empty states instead of fake data');
for(const required of ['.stitchAdminLayout{display:grid','.stitchAdminLayout nav button{','@media(max-width:820px)','.stitchAdminLayout>aside{display:none','.stitchAdminLayout>aside.is-open{display:block','grid-template-columns:repeat(2,minmax(0,1fr))','@media(prefers-reduced-motion:reduce)'])assert(css.includes(required),`missing mobile admin invariant: ${required}`);

const html=await readFile('dist/index.html','utf8');
const styles=[...html.matchAll(/href="(\/assets\/[^\"]+\.css)"/g)].map(match=>match[1]);
assert(styles.length>0,'production HTML must preload a main stylesheet');
const assets=await readdir('dist/assets');
const main=styles.map(path=>path.split('/').pop()).find(name=>assets.includes(name));
assert(main,'main stylesheet referenced by production HTML was not found');
const productionCss=await readFile('dist/assets/'+main,'utf8');
assert(productionCss.includes('.stitchAdminLayout')&&productionCss.includes('.stitchAdminLayout nav button'),'admin navigation CSS must be in the initial production stylesheet');
const catalogCss=assets.find(name=>name.startsWith('CatalogManagerV2-')&&name.endsWith('.css'));
assert(catalogCss,'lazy catalog stylesheet missing');
assert(productionCss.indexOf('.stitchAdminLayout nav button')>=0,'the scoped Stitch admin selector must be present in production');
console.log(JSON.stringify({ok:true,adminDestinations:12,initialCss:main,mobileMenu:true,verticalRail:true,reducedMotion:true,realDataOnly:true}));
